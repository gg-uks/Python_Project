import re
INVIS = re.compile('[\u200b\u200c\u200d\ufeff\u00a0]')   # 보이지 않는 문자 (zero-width · BOM · nbsp)
MEMO = r'(생략\s*가능|생략|선택\s*사항|선택|옵션|취향껏|취향것|기호에\s*따라(\s*조절)?|기호에따라|입맛에\s*맞게|입맛대로|원하는\s*만큼|먹고\s*싶은\s*만큼|다다익선|' \
       r'약간|약|넉넉히|넉넉하게|듬뿍|듬쁙|담뿍|가득|수북(하게|이)?|소복하게|볼록하게|크게|조금|톡톡톡?|갈갈|\*|' \
       r'손질\s*후|손질후|손질\s*전|데친\s*후|데친|삶은\s*후|불린\s*후|불리기\s*전|' \
       r'고명용|토핑용|데코용|장식용|데칠\s*때|데칠때|데칠용|데치기|삶을\s*때|삶기|절임용|절일\s*때|절이기|부침용|구이용|볶음용|튀김용|밑간용?|세척용|세척시|' \
       r'밥\s*숟가락(\s*계량|\s*기준)?|아빠\s*숟가락|숟가락|계량\s*스푼|종이컵|소주잔(\s*기준)?|국그릇(\s*기준)?|작은술|큰술|' \
       r'큐브|큐부|정도|대략|분알|몇\s*알|흰\s*부분|흰부분|흰대|초록\s*부분|초록부분|줄기\s*부분|줄기부분|밥\s*수저(\s*기준)?|기준)'
SIZE = r'(작은\s*(사이즈|크기|거|것|것으로)|작은|중간\s*(사이즈|크기|거)|중\s*사이즈|중사이즈|큰\s*(사이즈|거|것)|큰것|큰거|大|中|小|特|반개|반|한|두)'
AMT = r'\d+(\.\d+)?\s*(g|kg|ml|l|개|컵|큰술|작은술|T|t|cm|mm|봉|팩|장|알|줌)?'
ENG = r'\s+[A-Za-z][A-Za-z ]*$'

def clean(name):
    s = INVIS.sub('', name or '').strip()
    s = re.sub(r'^[-–•·]+|\s*-\s*$', '', s).strip()
    s = re.sub(r'^(구울때|밑간용|데칠때)\s*-\s*', '', s)
    s = re.sub(r'[()\[\]{}]', ' ', s).strip()               # 파프리카 (빨강) → 파프리카 빨강
    s = re.sub(r'\s*\+\s*물$', '', s)                          # 소고기 육수+물 → 소고기 육수
    s = re.sub(r'^(시판용|시판|집|얼린|냉동|채\s*썬|채썬|송송\s*썬|다진\s+|통|손질된|손질|중간입자|굵은입자|고운입자)\s+', '', s)   # 앞에 붙은 상태 · 손질 표현
    s = re.sub(ENG, '', s)                                    # 계란 Eggs → 계란
    s = re.split(r'\s+(?:또는|or|이나|나)\s+|또는|\s+or\s+|(?<=[가-힣])or(?=[가-힣])', s)[0]   # A 또는 B → A
    s = re.split(r'(?<=[가-힣])나\s+', s)[0]                    # 쪽파나 대파 → 쪽파
    s = re.sub(r'^이유식\s*(초기|중기|후기)\s*', '', s)
    s = re.sub(r'(?<=[가-힣])[大中小]$', '', s)
    s = re.sub(r'(생략\s*가능|선택\s*사항|선택|취향껏|대체\s*가능)$', '', s).strip()      # 붙어 쓴 메모
    for _ in range(3):
        s2 = re.sub(r'(\s+|^)' + MEMO + r'(?=\s|$)', ' ', s)
        s2 = re.sub(r'\s+' + SIZE + r'(?=\s|$)', ' ', s2)
        s2 = re.sub(r'\s*' + AMT + r'\s*$', '', s2)
        s2 = re.sub(r'\s+', ' ', s2).strip()
        if s2 == s: break
        s = s2
    return s.replace(' ', '')
